#!/usr/bin/env python3
"""Generate the table of $redirect= stub resources Paani can serve.

The stub files and their alias names come from Helium's bundled uBlock Origin
component:

  third_party/ublock/web_accessible_resources/   the stub payloads
  third_party/ublock/js/redirect-resources.js    the alias names filters use

Every payload is already inside resources.pak, so the table only has to map a
file name to the grit resource id generated for it by third_party/ublock:ublock.

Run after changing either source; the output is checked in.
"""

import argparse
import os
import re
import sys

ENTRY_RE = re.compile(r"\[\s*'([^']+)'\s*,\s*\{(.*?)\}\s*\]", re.DOTALL)
ALIAS_STR_RE = re.compile(r"alias:\s*'([^']*)'")
ALIAS_LIST_RE = re.compile(r"alias:\s*\[(.*?)\]", re.DOTALL)
ALIAS_ITEM_RE = re.compile(r"'([^']*)'")


def sanitize_to_macro_name(file_name):
    return "".join(
        c.upper() if c.isalnum() and c.isascii() else "_" for c in file_name
    )


def parse_alias_table(js_text):
    """Returns {file_name: [alias, ...]} from redirect-resources.js."""
    aliases = {}
    for name, body in ENTRY_RE.findall(js_text):
        found = []
        single = ALIAS_STR_RE.search(body)
        if single:
            found.append(single.group(1))
        listing = ALIAS_LIST_RE.search(body)
        if listing:
            found.extend(ALIAS_ITEM_RE.findall(listing.group(1)))
        aliases[name] = found
    return aliases


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ublock-dir", required=True)
    parser.add_argument("--out-dir", required=True)
    args = parser.parse_args()

    resource_dir = os.path.join(args.ublock_dir, "web_accessible_resources")
    js_path = os.path.join(args.ublock_dir, "js", "redirect-resources.js")

    with open(js_path, encoding="utf-8") as handle:
        aliases = parse_alias_table(handle.read())

    files = sorted(
        name
        for name in os.listdir(resource_dir)
        if name != "README.txt" and os.path.isfile(
            os.path.join(resource_dir, name)
        )
    )
    if not files:
        print("no stub resources found in " + resource_dir, file=sys.stderr)
        return 1

    unknown = sorted(name for name in files if name not in aliases)
    for name in unknown:
        aliases[name] = []

    lines = []
    lines.append("// Copyright 2026 The Paani Authors")
    lines.append(
        "// Use of this source code is governed by a GPL-3.0 license that can be"
    )
    lines.append("// found in the LICENSE file.")
    lines.append("")
    lines.append("// GENERATED by build/patchwork/make_redirect_resources.py")
    lines.append(
        "// Source: third_party/ublock/js/redirect-resources.js and"
    )
    lines.append("//         third_party/ublock/web_accessible_resources/")
    lines.append("// Do not edit.")
    lines.append("")
    lines.append('#include "chrome/browser/paani/adblock/paani_redirect_resources.h"')
    lines.append("")
    lines.append('#include "third_party/ublock/resources/grit/ublock_resources.h"')
    lines.append("")
    lines.append("namespace paani {")
    lines.append("")
    lines.append("namespace {")

    index = 0
    for name in files:
        entries = aliases[name]
        if entries:
            lines.append("const char* const kAliases%d[] = {" % index)
            for alias in entries:
                lines.append('    "%s",' % alias)
            lines.append("};")
        index += 1

    lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("const PaaniRedirectResource kPaaniRedirectResources[] = {")
    index = 0
    for name in files:
        entries = aliases[name]
        alias_expr = "kAliases%d" % index if entries else "nullptr"
        count_expr = str(len(entries)) if entries else "0"
        lines.append(
            '    {"%s", IDR_UBLOCK_WEB_ACCESSIBLE_RESOURCES_%s, %s, %s},'
            % (name, sanitize_to_macro_name(name), alias_expr, count_expr)
        )
        index += 1
    lines.append("};")
    lines.append("")
    # The count is a literal rather than std::size(), so the generated file
    # needs no <iterator> include of its own.
    lines.append(
        "const size_t kPaaniRedirectResourceCount = %d;" % len(files)
    )
    lines.append("")
    lines.append("}  // namespace paani")
    lines.append("")

    os.makedirs(args.out_dir, exist_ok=True)
    out_path = os.path.join(args.out_dir, "paani_redirect_resources.cc")
    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))

    total_aliases = sum(len(aliases[name]) for name in files)
    print("wrote %s" % out_path)
    print("resources: %d, aliases: %d, unlisted files: %d"
          % (len(files), total_aliases, len(unknown)))
    if unknown:
        print("no alias entry for: %s" % ", ".join(unknown))
    return 0


if __name__ == "__main__":
    sys.exit(main())
